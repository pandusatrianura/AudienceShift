package inspector

import (
	"encoding/json"
	"fmt"
	"strings"
)

// PostmanCollectionV2 represents the schema for Postman Collection v2.1.0.
type PostmanCollectionV2 struct {
	Info PostmanInfo   `json:"info"`
	Item []PostmanItem `json:"item"`
}

type PostmanInfo struct {
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	Schema      string `json:"schema"`
}

type PostmanItem struct {
	Name    string         `json:"name"`
	Request PostmanRequest `json:"request"`
}

type PostmanRequest struct {
	Method string          `json:"method"`
	Header []PostmanHeader `json:"header"`
	Body   PostmanBody     `json:"body"`
	URL    PostmanURL      `json:"url"`
}

type PostmanHeader struct {
	Key   string `json:"key"`
	Value string `json:"value"`
}

type PostmanBody struct {
	Mode string `json:"mode"`
	Raw  string `json:"raw"`
}

type PostmanURL struct {
	Raw  string   `json:"raw"`
	Host []string `json:"host"`
	Path []string `json:"path"`
}

// ExportJSON serializes recorded webhook events to a pretty-printed JSON document.
// If includeSecrets is false, sensitive headers are masked to prevent credential leaks.
func ExportJSON(events []*WebhookEvent, includeSecrets bool) ([]byte, error) {
	if includeSecrets {
		return json.MarshalIndent(events, "", "  ")
	}

	sanitized := make([]*WebhookEvent, len(events))
	for i, e := range events {
		clone := *e
		clone.Request.Headers = e.Request.MaskedHeaders()
		sanitized[i] = &clone
	}
	return json.MarshalIndent(sanitized, "", "  ")
}

// ExportPostman converts recorded webhook events into a ready-to-import Postman Collection v2.1.
func ExportPostman(events []*WebhookEvent, collectionName string) ([]byte, error) {
	if collectionName == "" {
		collectionName = "AudienceShift Webhooks"
	}

	col := PostmanCollectionV2{
		Info: PostmanInfo{
			Name:        collectionName,
			Description: "Exported webhook traces generated by AudienceShift",
			Schema:      "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
		},
		Item: make([]PostmanItem, 0, len(events)),
	}

	for _, e := range events {
		var headers []PostmanHeader
		masked := e.Request.MaskedHeaders()
		for k, vv := range masked {
			for _, v := range vv {
				headers = append(headers, PostmanHeader{
					Key:   k,
					Value: v,
				})
			}
		}

		rawPath := strings.TrimPrefix(e.Request.Path, "/")
		pathSegments := strings.Split(rawPath, "/")
		if len(pathSegments) == 1 && pathSegments[0] == "" {
			pathSegments = []string{}
		}

		rawURL := "{{base_url}}" + e.Request.Path
		if e.Request.Query != "" {
			rawURL += "?" + e.Request.Query
		}

		bodyStr := string(e.Request.Body)

		item := PostmanItem{
			Name: fmt.Sprintf("[%s] %s %s", strings.ToUpper(e.Provider), e.Request.Method, e.Request.Path),
			Request: PostmanRequest{
				Method: e.Request.Method,
				Header: headers,
				Body: PostmanBody{
					Mode: "raw",
					Raw:  bodyStr,
				},
				URL: PostmanURL{
					Raw:  rawURL,
					Host: []string{"{{base_url}}"},
					Path: pathSegments,
				},
			},
		}
		col.Item = append(col.Item, item)
	}

	return json.MarshalIndent(col, "", "  ")
}
